"""Profile-to-target emission pipeline for Limen partner devices.

Compilation is organized as an emitter registry: each target declares a small
render function and the pipeline runs them in a fixed order, so output is
byte-stable across runs. The generated C and Verilog are review artifacts for
integration; the generator makes no MISRA certification, RTL verification, or
production-readiness claim.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Mapping

from .schema import ActuatorSpec, PartnerProfile


def _stable_dump(document: object) -> str:
    serialized = json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return serialized + "\n"


def _guard_token(identifier: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", identifier).upper()


def _c_literal(quantity: float) -> str:
    return f"{quantity:.6f}F"


@dataclass(frozen=True)
class CompilationArtifacts:
    """The full set of targets emitted for one profile."""

    profile_id: str
    files: Mapping[str, str]

    def write(self, output_dir: Path) -> tuple[Path, ...]:
        output_dir.mkdir(parents=True, exist_ok=True)
        destinations: list[Path] = []
        for target in sorted(self.files):
            destination = output_dir.joinpath(target)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(self.files[target], encoding="utf-8", newline="\n")
            destinations.append(destination)
        return tuple(destinations)


def _emit_simulation(profile: PartnerProfile) -> str:
    runtime_flags = dict(
        quality_gate="confidence_coupled_safety_envelope",
        unknown_intent_action="safe_halt",
        hardware_supervisor="enabled",
    )
    document = dict(target="simulation", profile=profile.to_mapping(), runtime=runtime_flags)
    return _stable_dump(document)


def _firmware_preamble(guard: str) -> str:
    banner = "/* Generated by limen.profile. Reference artifact; review before target integration. */\n"
    notice = "/* No certification or complete MISRA-C claim is made by this generator. */\n"
    opening = banner + notice
    opening += f"#ifndef LIMEN_PROFILE_{guard}_H\n#define LIMEN_PROFILE_{guard}_H\n\n"
    opening += "#include <stdint.h>\n"
    return opening


def _firmware_constants(profile: PartnerProfile, limits: ActuatorSpec) -> str:
    block = "\n#define LIMEN_PROFILE_SCHEMA_MAJOR (1U)\n"
    block += f"#define LIMEN_PROFILE_SENSOR_COUNT ({len(profile.sensors)}U)\n"
    block += f"#define LIMEN_PROFILE_INTENT_COUNT ({len(profile.intent_classes)}U)\n"
    block += f"#define LIMEN_PROFILE_MAX_TORQUE_NM ({_c_literal(limits.max_torque_nm)})\n"
    block += f"#define LIMEN_PROFILE_MAX_VELOCITY_RAD_S ({_c_literal(limits.max_velocity_rad_s)})\n"
    return block


def _firmware_limits_struct(limits: ActuatorSpec) -> str:
    fields = (
        "    float max_torque_nm;\n"
        "    float max_velocity_rad_s;\n"
        "    float position_min_rad;\n"
        "    float position_max_rad;\n"
    )
    struct = "\ntypedef struct\n{\n" + fields + "} limen_actuator_limits_t;\n"
    values = (
        f"    {_c_literal(limits.max_torque_nm)},\n"
        f"    {_c_literal(limits.max_velocity_rad_s)},\n"
        f"    {_c_literal(limits.position_min_rad)},\n"
        f"    {_c_literal(limits.position_max_rad)}\n"
    )
    struct += "\nstatic const limen_actuator_limits_t limen_actuator_limits =\n{\n" + values + "};\n"
    return struct


def _emit_firmware(profile: PartnerProfile) -> str:
    guard = _guard_token(profile.profile_id)
    text = _firmware_preamble(guard)
    text += _firmware_constants(profile, profile.actuator)
    text += _firmware_limits_struct(profile.actuator)
    text += f"\n#endif /* LIMEN_PROFILE_{guard}_H */\n\n"
    return text


def _emit_rtl(profile: PartnerProfile) -> str:
    guard = _guard_token(profile.profile_id)
    scaled_torque = round(profile.actuator.max_torque_nm * 1000.0)
    scaled_velocity = round(profile.actuator.max_velocity_rad_s * 1_000_000.0)
    note = "// Generated by limen.profile. Reference parameters; not verified RTL.\n"
    note += f"// Profile: {profile.profile_id}\n"
    note += f"localparam integer LIMEN_{guard}_SENSOR_COUNT = {len(profile.sensors)};\n"
    note += f"localparam integer LIMEN_{guard}_INTENT_COUNT = {len(profile.intent_classes)};\n"
    note += f"localparam integer LIMEN_{guard}_MAX_TORQUE_MNM = {scaled_torque};\n"
    note += f"localparam integer LIMEN_{guard}_MAX_VELOCITY_URAD_S = {scaled_velocity};\n\n"
    return note


def _sensor_fault_cases(profile: PartnerProfile) -> list[dict]:
    cases: list[dict] = []
    for route in profile.fault_paths:
        fault_detail = dict(sensor=route.sensor, condition="disconnect")
        cases.append(
            dict(
                id=f"sensor_{route.sensor}_failure",
                fault=fault_detail,
                expected_action=route.action,
            )
        )
    return cases


def _actuator_fault_cases(limits: ActuatorSpec) -> list[dict]:
    over_torque = dict(
        id="actuator_torque_over_limit",
        fault=dict(actuator=limits.name, torque_nm=limits.max_torque_nm + 1.0),
        expected_action="safe_halt",
    )
    over_velocity = dict(
        id="actuator_velocity_over_limit",
        fault=dict(actuator=limits.name, velocity_rad_s=limits.max_velocity_rad_s + 1.0),
        expected_action="safe_halt",
    )
    return [over_torque, over_velocity]


def _emit_vectors(profile: PartnerProfile) -> str:
    cases = _sensor_fault_cases(profile) + _actuator_fault_cases(profile.actuator)
    document = dict(profile_id=profile.profile_id, vectors=cases)
    return _stable_dump(document)


# Emitter registry: target filename to render function, in pipeline order.
_EMITTERS: tuple[tuple[str, Callable[[PartnerProfile], str]], ...] = (
    ("simulation_profile.json", _emit_simulation),
    ("firmware_profile.h", _emit_firmware),
    ("rtl_profile.vh", _emit_rtl),
    ("fault_test_vectors.json", _emit_vectors),
)


class ProfileCompiler:
    """Run every registered emitter against one validated profile."""

    def compile(self, profile: PartnerProfile) -> CompilationArtifacts:
        rendered = {target: emit(profile) for target, emit in _EMITTERS}
        return CompilationArtifacts(profile.profile_id, rendered)
